export function getDemoDashboard(params = {}) {
  const filtered = filterDemoSales(params);
  const totalRevenue = filtered.reduce((sum, item) => sum + Number(item.sales || 0), 0);
  const totalProfit = filtered.reduce((sum, item) => sum + Number(item.profit || 0), 0);
  const totalOrders = filtered.length;
  const totalQuantity = filtered.reduce((sum, item) => sum + Number(item.quantity || 0), 0);

  const categoryMap = {};
  filtered.forEach(item => {
    if (!categoryMap[item.category]) categoryMap[item.category] = { category: item.category, revenue: 0, profit: 0 };
    categoryMap[item.category].revenue += Number(item.sales || 0);
    categoryMap[item.category].profit += Number(item.profit || 0);
  });

  const monthMap = {};
  filtered.forEach(item => {
    const month = (item.orderDate || '').slice(0, 7);
    if (!month) return;
    if (!monthMap[month]) monthMap[month] = { month, revenue: 0, quantity: 0 };
    monthMap[month].revenue += Number(item.sales || 0);
    monthMap[month].quantity += Number(item.quantity || 0);
  });

  const months = Object.keys(monthMap).sort();
  const revenueTrend = months.map(m => ({ month: m, revenue: monthMap[m].revenue }));
  const salesTrend = months.map(m => ({ month: m, sales: monthMap[m].quantity }));

  return {
    summary: {
      totalRevenue,
      totalProfit,
      totalOrders,
      totalQuantity,
      avgOrderValue: totalOrders ? totalRevenue / totalOrders : 0,
      demoData: true
    },
    revenueTrend,
    salesTrend,
    categoryBreakdown: Object.values(categoryMap),
    productPerformance: DEMO_PRODUCTS,
    seasonalPattern: [
      { month: 'Jan', revenue: 24759 },
      { month: 'Feb', revenue: 11398 },
      { month: 'Mar', revenue: 13285 },
      { month: 'Apr', revenue: 9720 },
      { month: 'May', revenue: 10810 },
      { month: 'Jun', revenue: 6717 },
      { month: 'Jul', revenue: 8392 },
      { month: 'Aug', revenue: 7290 },
      { month: 'Sep', revenue: 1488 },
      { month: 'Oct', revenue: 5090 },
      { month: 'Nov', revenue: 7620 },
      { month: 'Dec', revenue: 3545 }
    ],
    demoData: true
  };
}

export function filterDemoSales(params = {}) {
  let list = [...DEMO_SALES];
  if (params.category) list = list.filter(item => item.category === params.category);
  if (params.product) list = list.filter(item => item.productName === params.product);
  if (params.region) list = list.filter(item => item.region === params.region);
  if (params.search) {
    const q = params.search.toLowerCase();
    list = list.filter(item =>
      item.productName.toLowerCase().includes(q) ||
      item.customerName.toLowerCase().includes(q) ||
      item.orderId.toLowerCase().includes(q)
    );
  }
  return list;
}
